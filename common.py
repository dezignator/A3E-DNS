def fit_logreg(X, y, lr=0.2, epochs=2500, l2=1e-4, seed=0, adv_eps=0.0, adv_steps=0, batch=256, hidden=16):
    """Mini-batch SGD with momentum on the MLP detector; optional PGD adversarial training (L_inf, standardised units)."""
    r = np.random.default_rng(seed); m = MLPModel(X.shape[1], hidden, seed); v = np.zeros_like(m.w)
    for ep in range(epochs):
        idx = r.integers(0, len(X), batch); Xb, yb = X[idx], y[idx]
        if adv_eps > 0 and ep > epochs // 5: Xb = pgd(m, Xb, yb, adv_eps, adv_steps or 5)
        v = 0.9 * v + 0.1 * m.grad(Xb, yb, l2); m.w -= lr * 5 * v * (0.4 if ep > epochs // 2 else 1.0)
    return m

def pgd(m, X, y, eps, steps=10, alpha=None):
    alpha = alpha or 2.5 * eps / steps; Xa = X.copy()
    for _ in range(steps):
        g = m.input_grad(Xa, y); Xa = np.clip(Xa + alpha * np.sign(g), X - eps, X + eps)
    return Xa

def build(seed, n_per_class=400, severity=1.0, scenarios=None):
    r = np.random.default_rng(seed)
    X, y, p, s = T.make_dataset(n_per_class, r, scenarios=scenarios, severity=severity)
    tr, va, te = T.split(X, y, r); mu, sd = X[tr].mean(0), X[tr].std(0) + 1e-9
    Z = (X - mu) / sd
    return dict(X=X, Z=Z, y=y, p=p, s=s, tr=tr, va=va, te=te, mu=mu, sd=sd, rng=r)

def prf(y, yp):
    tp = ((yp == 1) & (y == 1)).sum(); fp = ((yp == 1) & (y == 0)).sum(); fn = ((yp == 0) & (y == 1)).sum(); tn = ((yp == 0) & (y == 0)).sum()
    pr = tp / max(tp + fp, 1); rc = tp / max(tp + fn, 1)
    return dict(precision=pr, recall=rc, f1=2 * pr * rc / max(pr + rc, 1e-12), fpr=fp / max(fp + tn, 1), acc=(tp + tn) / len(y))

def ci(x):
    x = np.asarray(x, float); h = 1.96 * x.std(ddof=1) / np.sqrt(len(x)) if len(x) > 1 else 0.0; return x.mean(), h

def federate(D, K, seed, per_client=120, alpha=0.5):
    """Non-IID partition of the training pool over K clients (Dirichlet over protocols)."""
    r = np.random.default_rng(seed); tr = D["tr"]; Xs, ys = [], []
    by = [tr[D["p"][tr] == i] for i in range(3)]
    for k in range(K):
        w = r.dirichlet([alpha] * 3); cnt = r.multinomial(per_client, w); idx = np.concatenate([r.choice(by[i], c) for i, c in enumerate(cnt)])
        Xs.append(D["X"][idx]); ys.append(D["y"][idx])
    return Xs, ys
