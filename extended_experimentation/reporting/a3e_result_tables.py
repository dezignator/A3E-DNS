def _build_s1(payload: Optional[Mapping[str, object]]) -> str:
    if not payload:
        return "% S1: missing manifest\n"
    rows = []
    for entry in payload.get("scenarios", []):  # type: ignore[assignment]
        rows.append(
            [
                str(entry.get("scenario_id", "")),
                str(entry.get("variant", "")),
                f"{float(entry.get('accuracy', 0.0)):.6f}",
                f"{float(entry.get('fpr', 0.0)):.6f}",
                f"{int(entry.get('n_windows', 0))}",
            ]
        )
    return _render_table(
        title=str(TABLE_SPECS["S1"]["title"]),
        header=["Scenario", "Variant", "Accuracy", "FPR", "n"],
        rows=rows,
    )


