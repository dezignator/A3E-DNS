# --------------------------------------------------------------------------- #
# Driver
# --------------------------------------------------------------------------- #


def generate_tables(
    manifests_root: Path,
    out_dir: Path,
) -> Dict[str, object]:
    root = Path(manifests_root)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: List[str] = []
    missing: List[str] = []
    for name, spec in TABLE_SPECS.items():
        manifest_path = root / str(spec["manifest"])
        payload = _load_json(manifest_path)
        if payload is None:
            missing.append(name)
        builder = _BUILDERS[name]
        tex = builder(payload)
        target = out / f"table_{name}.tex"
        target.write_text(tex)
        written.append(str(target))
    manifest: Dict[str, object] = {
        "module": "extended_experimentation.reporting.a3e_result_tables",
        "tables_written": written,
        "tables_missing": missing,
        "thesis_reference": THESIS_REFERENCE,
    }
    manifest["manifest_sha256"] = hashlib.sha256(
        json.dumps(manifest, sort_keys=True, default=str).encode("utf-8")
    ).hexdigest()
    (out / "tables_manifest.json").write_text(json.dumps(manifest, indent=2))
    LOGGER.info(
        "generated %d tables; %d missing manifests: %s",
        len(written), len(missing), ", ".join(missing) or "none",
    )
    return manifest


# --------------------------------------------------------------------------- #
# CLI
